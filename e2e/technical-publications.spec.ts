import { test, expect } from '@playwright/test';

test.describe('Issue #5: Technical Publications & Build-Time Syntax Highlighting', () => {
  test('/posts lists published articles, excludes drafts, and filters by tag', async ({
    page,
  }) => {
    const response = await page.goto('/posts');
    expect(response?.status()).toBe(200);

    const postArticles = page.locator('article[data-post-item="true"]');
    const count = await postArticles.count();
    expect(count).toBeGreaterThanOrEqual(2);

    // Assert draft article is NOT present
    const content = await page.content();
    expect(content).not.toContain('DRAFT: Internal Work in Progress');

    // First article has title, date, reading time, tags
    const firstArticle = postArticles.first();
    await expect(firstArticle.locator('h2')).toBeVisible();
    await expect(firstArticle.locator('time')).toBeVisible();
    await expect(firstArticle.locator('[data-reading-time="true"]')).toBeVisible();

    // Tag filtering functionality
    const linuxTagButton = page.locator('button[data-filter="Linux"]');
    await expect(linuxTagButton).toBeVisible();
    await linuxTagButton.click();

    // Verify visible articles contain Linux tag
    const visiblePosts = page.locator('article[data-post-item="true"]:not(.hidden)');
    expect(await visiblePosts.count()).toBeGreaterThanOrEqual(1);

    // Click 'All' filter restores full list
    const allFilterButton = page.locator('button[data-filter="all"]');
    await allFilterButton.click();
    expect(await page.locator('article[data-post-item="true"]:not(.hidden)').count()).toBe(count);
  });

  test('/posts/[slug] renders deep technical article with build-time syntax highlighting', async ({
    page,
  }) => {
    await page.goto('/posts');

    // Click the first article link
    const firstLink = page
      .locator('article[data-post-item="true"]')
      .first()
      .locator('a[data-post-link="true"]')
      .first();
    await firstLink.click();

    await expect(page).toHaveURL(/\/posts\/.+/);

    // Article heading & prose structure
    const article = page.locator('article');
    await expect(article).toBeVisible();
    await expect(article.locator('h1')).toBeVisible();

    // Syntax-highlighted code block generated by Shiki at build time
    const codeBlock = page.locator('pre.astro-code');
    await expect(codeBlock.first()).toBeVisible();

    // Verify token spans with Shiki CSS variables exist
    const tokenSpans = codeBlock.first().locator('span');
    expect(await tokenSpans.count()).toBeGreaterThan(5);
  });

  test('homepage displays recent non-draft posts', async ({ page }) => {
    await page.goto('/');

    const postsSection = page.locator('#posts');
    await expect(postsSection).toBeVisible();

    const postItems = postsSection.locator('#posts-list > article');
    expect(await postItems.count()).toBeGreaterThanOrEqual(1);
  });
});
